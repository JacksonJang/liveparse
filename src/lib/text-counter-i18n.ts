const NUMBER_LOCALES: Record<TextCounterUiLocale, string> = {
  en: 'en-US',
  es: 'es-ES',
  ja: 'ja-JP',
  ko: 'ko-KR',
};

export function resolveTextCounterUiLocale(value: string | undefined): TextCounterUiLocale {
  const primaryLanguage = value?.trim().toLowerCase().replace('_', '-').split('-')[0];
  return primaryLanguage === 'es' || primaryLanguage === 'ja' || primaryLanguage === 'ko'
    ? primaryLanguage
    : 'en';
}

export function getTextCounterMessages(locale: TextCounterUiLocale): TextCounterMessages {
  return MESSAGE_SETS[locale];
}

export function getTextCounterNumberLocale(locale: TextCounterUiLocale): string {
  return NUMBER_LOCALES[locale];
}

export function formatTextCounterMessage(
  template: string,
  values: Readonly<Record<string, string | number>>,
): string {
  return template.replace(/\{([a-z]+)\}/gi, (placeholder, key: string) => (
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : placeholder
  ));
}

export function resolveTextCounterAnalysisLocale(value: string | undefined): string {
  return value?.trim() || 'auto';
}

export function resolveTextCounterCharacterLimit(value: string | undefined): number {
  const parsed = Number(value);
  return Number.isInteger(parsed) && parsed >= 1 && parsed <= 1_000_000 ? parsed : 280;
}

export interface JapaneseManuscriptEstimate {
  readonly fullSheets: number;
  readonly remainderCharacters: number;
}

export function calculateJapaneseManuscriptEstimate(graphemeClusters: number): JapaneseManuscriptEstimate {
  if (!Number.isSafeInteger(graphemeClusters) || graphemeClusters < 0) {
    throw new RangeError('Grapheme count must be a non-negative safe integer.');
  }
  return {
    fullSheets: Math.floor(graphemeClusters / 400),
    remainderCharacters: graphemeClusters % 400,
  };
}

export interface KoreanAsciiWeightedCount {
  readonly weightedCount: number;
  readonly asciiCodePoints: number;
  readonly nonAsciiCodePoints: number;
}

/**
 * Applies an explicit display policy, not a byte encoding: each ASCII code
 * point is worth one unit and every non-ASCII code point is worth two.
 */
export function calculateKoreanAsciiWeightedCount(input: string): KoreanAsciiWeightedCount {
  let weightedCount = 0;
  let asciiCodePoints = 0;
  let nonAsciiCodePoints = 0;

  for (const codePoint of input) {
    if ((codePoint.codePointAt(0) ?? 0) <= 0x7f) {
      asciiCodePoints += 1;
      weightedCount += 1;
    } else {
      nonAsciiCodePoints += 1;
      weightedCount += 2;
    }
  }

  return { weightedCount, asciiCodePoints, nonAsciiCodePoints };
}
